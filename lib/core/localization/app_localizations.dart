  // --- Devanagari Digit Conversion ---
  static const Map<String, String> _devanagariDigits = {
    '0': '०',
    '1': '१',
    '2': '२',
    '3': '३',
    '4': '४',
    '5': '५',
    '6': '६',
    '7': '७',
    '8': '८',
    '9': '९',
  };

  String toDevanagariDigits(String input) {
    String res = input;
    _devanagariDigits.forEach((key, value) {
      res = res.replaceAll(key, value);
    });
    return res;
  }

